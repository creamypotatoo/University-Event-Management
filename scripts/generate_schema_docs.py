"""Regenerate the schema reference and ER diagram directly from model metadata."""

from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import CheckConstraint, UniqueConstraint
from sqlalchemy.dialects import postgresql
from app import models
from app.extensions import db

root = Path(__file__).resolve().parents[1] / "docs"
root.mkdir(exist_ok=True)
schema = ["# Schema reference", "", "Generated from `app/models.py` by `python scripts/generate_schema_docs.py`.", "",
          "All columns are NOT NULL. All foreign keys use ON DELETE RESTRICT. Integer primary keys are generated by PostgreSQL sequences.", "",
          "Timestamps use TIMESTAMP WITH TIME ZONE; PostgreSQL stores instants, and display should convert to Asia/Dhaka. Money uses NUMERIC(12,2), assumed BDT.", ""]
diagram = ["erDiagram"]
for table in db.metadata.sorted_tables:
    schema.extend([f"## {table.name}", "", "| Column | PostgreSQL type | Key / default |", "| --- | --- | --- |"])
    diagram.append(f"    {table.name} {{")
    for column in table.columns:
        keys = []
        if column.primary_key: keys.append("PK")
        if column.foreign_keys: keys.append("FK")
        if (any(isinstance(c, UniqueConstraint) and len(c.columns) == 1 and column.name in c.columns for c in table.constraints)
                or any(i.unique and len(i.columns) == 1 and column.name in i.columns for i in table.indexes)):
            keys.append("UK")
        if column.server_default is not None: keys.append(f"default `{column.server_default.arg}`")
        foreign = ", ".join(f"references {fk.target_fullname}" for fk in column.foreign_keys)
        schema.append(f"| {column.name} | {column.type.compile(dialect=postgresql.dialect())} | {'; '.join(keys + ([foreign] if foreign else []))} |")
        er_type = str(column.type).split("(")[0].lower().replace(" ", "_")
        er_keys = [k for k in keys if k in {"PK", "FK", "UK"}]
        diagram.append(f"        {er_type} {column.name}" + (" " + ",".join(er_keys) if er_keys else ""))
    diagram.append("    }")
    schema.extend(["", "Constraints:", ""])
    for constraint in sorted(table.constraints, key=lambda c: str(c.name)):
        if isinstance(constraint, CheckConstraint): schema.append(f"- `{constraint.name}`: `{constraint.sqltext}`")
        if isinstance(constraint, UniqueConstraint): schema.append(f"- `{constraint.name}`: UNIQUE ({', '.join(c.name for c in constraint.columns)})")
    schema.extend(["", "Indexes (in addition to primary/unique constraint indexes):", ""])
    for index in sorted(table.indexes, key=lambda i: i.name):
        schema.append(f"- `{index.name}`: {'UNIQUE ' if index.unique else ''}({', '.join(c.name for c in index.columns)})")
    if table.name == "events":
        schema.extend(["- `ex_events_venue_time`: PostgreSQL GiST exclusion on venue equality and overlapping `tstzrange(start_time, end_time, '[)')`, WHERE status <> 'cancelled'. This creates its own GiST index."])
    schema.append("")
    for column in table.columns:
        for foreign in column.foreign_keys:
            unique = column.unique or any(isinstance(c, UniqueConstraint) and len(c.columns) == 1 and column.name in c.columns for c in table.constraints)
            diagram.append(f"    {foreign.column.table.name} ||--{'o|' if unique else 'o{'} {table.name} : {column.name}")

(root / "schema.md").write_text("\n".join(schema) + "\n", encoding="utf-8")
(root / "er-diagram.mmd").write_text("\n".join(diagram) + "\n", encoding="utf-8")
(root / "er-diagram.md").write_text("# Entity relationship diagram\n\n```mermaid\n" + "\n".join(diagram) + "\n```\n", encoding="utf-8")
print("Generated docs/schema.md and Mermaid ER diagram.")
